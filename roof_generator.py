# ════════════════════════════════════════════════════════════════════
#  1. FOOTPRINT EXTRACTION
# ════════════════════════════════════════════════════════════════════
def extract_footprint(walls, scale=0.01):
    """Union all wall boxes and close them into a filled polygon.
    Robust to detection gaps: wall boxes from YOLO rarely touch
    perfectly, so we close the union with progressively larger
    morphological radii until it forms one connected outline."""
    boxes = []
    for w in walls:
        cx, cy = w["pos"][0] * scale, w["pos"][1] * scale
        ww, hh = w["w"] * scale, w["h"] * scale
        boxes.append(shp_box(cx - ww / 2, cy - hh / 2, cx + ww / 2, cy + hh / 2))
    if not boxes:
        return None
    raw = unary_union(boxes)
    total_area = sum(b.area for b in boxes)
    merged = None
    for r in (0.20, 0.45, 0.80, 1.30):
        closed = raw.buffer(r, join_style=2).buffer(-r, join_style=2)
        if isinstance(closed, MultiPolygon):
            largest = max(closed.geoms, key=lambda g: g.area)
            # accept only if the fragment clearly dominates
            if largest.area > 0.85 * sum(g.area for g in closed.geoms):
                merged = largest
                break
        else:
            merged = closed
            break
    if merged is None:  # still fragmented → take the largest piece
        closed = raw.buffer(1.3, join_style=2).buffer(-1.3, join_style=2)
        merged = max(closed.geoms, key=lambda g: g.area) \
            if isinstance(closed, MultiPolygon) else closed
    # fill interior holes (wall boxes form a ring; we want the filled plan)
    filled = Polygon(merged.exterior)
    filled = filled.simplify(0.12, preserve_topology=True)
    # snap to an orthogonal-ish polygon by rounding coords
    snapped = Polygon([(round(x, 1), round(y, 1)) for x, y in filled.exterior.coords])
    if not snapped.is_valid or snapped.area < 1.0:
        snapped = filled if filled.is_valid else filled.buffer(0)
    # sanity: the filled plan must cover at least the wall material itself
    if snapped.area < total_area:
        snapped = Polygon(raw.convex_hull.exterior)
    return snapped


def footprint_metrics(poly):
    minx, miny, maxx, maxy = poly.bounds
    w, h = maxx - minx, maxy - miny
    hull = poly.convex_hull
    return {
        "width": w, "depth": h,
        "aspect": max(w, h) / max(min(w, h), 1e-6),
        "area": poly.area,
        "convexity": poly.area / max(hull.area, 1e-6),   # <0.9 → L/T/U shape
        "bounds": (minx, miny, maxx, maxy),
    }


def decompose_wings(poly, max_wings=3, min_area_frac=0.12):
    """Greedy maximal-rectangle decomposition of an orthogonal polygon.
    Returns a list of (minx, miny, maxx, maxy) wing rectangles."""
    xs = sorted({round(x, 1) for x, _ in poly.exterior.coords})
    ys = sorted({round(y, 1) for _, y in poly.exterior.coords})
    # occupancy grid over the coordinate lattice
    cells = {}
    for i in range(len(xs) - 1):
        for j in range(len(ys) - 1):
            cx, cy = (xs[i] + xs[i + 1]) / 2, (ys[j] + ys[j + 1]) / 2
            cells[(i, j)] = poly.buffer(0.05).contains(Point(cx, cy))

    def rect_area(i0, j0, i1, j1):
        return (xs[i1 + 1] - xs[i0]) * (ys[j1 + 1] - ys[j0])

    wings, remaining = [], dict(cells)
    for _ in range(max_wings):
        best, best_a = None, 0.0
        n, m = len(xs) - 1, len(ys) - 1
        for i0 in range(n):
            for j0 in range(m):
                if not remaining.get((i0, j0)):
                    continue
                i1 = i0
                while i1 + 1 < n and remaining.get((i1 + 1, j0)):
                    i1 += 1
                for ii1 in range(i0, i1 + 1):
                    j1 = j0
                    while j1 + 1 < m and all(remaining.get((k, j1 + 1))
                                             for k in range(i0, ii1 + 1)):
                        j1 += 1
                    a = rect_area(i0, j0, ii1, j1)
                    if a > best_a:
                        best_a, best = a, (i0, j0, ii1, j1)
        if best is None or best_a < poly.area * min_area_frac:
            break
        i0, j0, i1, j1 = best
        wings.append((xs[i0], ys[j0], xs[i1 + 1], ys[j1 + 1]))
        for k in range(i0, i1 + 1):
            for l in range(j0, j1 + 1):
                remaining[(k, l)] = False
        if not any(remaining.values()):
            break
    if not wings:
        wings = [poly.bounds]
    return wings


