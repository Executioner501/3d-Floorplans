def _dormer(cx, ey, face_dir, slope_pitch, base_z, color,
            w=1.15, h=1.05, depth=1.25, axis="y"):
    """Small gabled dormer poking out of a roof slope.
    axis="y": sits on a ±Y eave line (ey is that y, cx the position along it,
              face_dir=+1 faces +Y).
    axis="x": sits on a ±X eave line (ey is that x, cx the position along it,
              face_dir=+1 faces +X)."""
    parts = []
    t = np.tan(np.radians(slope_pitch))
    inset = depth * 0.55
    zc = base_z + inset * t + 0.25
    # build in a local frame: window face at y=0, body RECESSED into the
    # roof (toward -Y*face_dir) so the dormer sits ON the slope instead
    # of hovering past the eave line.
    body = trimesh.creation.box(extents=(w, depth, h))
    body.apply_translation([0, -face_dir * (depth / 2 - 0.05), zc])
    parts.append(_colored(body, WALL_COLOR))
    # window, proud of the dormer face
    win = trimesh.creation.box(extents=(w * 0.55, 0.06, h * 0.55))
    win.apply_translation([0, face_dir * 0.09, zc])
    parts.append(_colored(win, GLASS_COLOR))
    # mini gable cap (prism ridge natively along Y = out of the roof face)
    prof = _gable_profile(w + 0.3, (w / 2) * np.tan(np.radians(slope_pitch * 0.9)), 0.08)
    cap = _prism_from_profile(prof, depth + 0.3, color)
    cap.apply_translation([0, -(depth + 0.3) / 2, 0])
    cap.apply_transform(trimesh.transformations.rotation_matrix(
        0 if face_dir > 0 else np.pi, [0, 0, 1]))
    cap.apply_translation([0, -face_dir * (depth / 2 - 0.05), zc + h / 2 - 0.04])
    parts.append(cap)
    # move the whole dormer to its eave: rotate local +Y onto +X if needed
    T = np.eye(4)
    if axis == "x":
        T = trimesh.transformations.rotation_matrix(-np.pi / 2, [0, 0, 1])
        T[:3, 3] = [ey, cx, 0]
    else:
        T[:3, 3] = [cx, ey, 0]
    for m in parts:
        m.apply_transform(T)
    return parts


def _chimney(cx, cy, top_z, color=CHIMNEY_COLOR, size=0.55):
    parts = []
    body = trimesh.creation.box(extents=(size, size, top_z + 0.9))
    body.apply_translation([cx, cy, (top_z + 0.9) / 2])
    parts.append(_colored(body, color))
    cap = trimesh.creation.box(extents=(size + 0.18, size + 0.18, 0.10))
    cap.apply_translation([cx, cy, top_z + 0.95])
    parts.append(_colored(cap, [90, 90, 95, 255]))
    return parts


def _skylight(cx, cy, z, w=0.9, d=1.3):
    frame = trimesh.creation.box(extents=(w, d, 0.16))
    frame.apply_translation([cx, cy, z + 0.08])
    glass = trimesh.creation.box(extents=(w * 0.8, d * 0.8, 0.06))
    glass.apply_translation([cx, cy, z + 0.19])
    return [_colored(frame, [70, 70, 75, 255]), _colored(glass, GLASS_COLOR)]


# ════════════════════════════════════════════════════════════════════
#  4. TOP-LEVEL GENERATION
# ════════════════════════════════════════════════════════════════════
def _coverage_gap(parts, poly, wall_h, res=96, margin=0.45):
    """Fraction of the footprint interior left unroofed. Uses the same
    z-buffer rasterizer as the diffusion bridge; anything below the wall
    top means rain gets in — the reconstruction failed there."""
    meshes = [m for m in parts if isinstance(m, trimesh.Trimesh)]
    if not meshes:
        return 1.0
    inner = poly.buffer(-margin, join_style=2)
    if inner.is_empty:
        return 0.0
    x0, y0, x1, y1 = poly.bounds
    hm = rasterize_roof_heightmap(meshes, (x0 - 0.5, y0 - 0.5,
                                           x1 + 0.5, y1 + 0.5), res=res)
    xs = np.linspace(x0 - 0.5, x1 + 0.5, res)
    ys = np.linspace(y0 - 0.5, y1 + 0.5, res)
    total = uncovered = 0
    for j, y in enumerate(ys):
        for i, x in enumerate(xs):
            if inner.contains(Point(x, y)):
                total += 1
                if hm[j, i] < wall_h + 0.02:
                    uncovered += 1
    return uncovered / max(total, 1)


def generate_roof(walls, params, scale=0.01, wall_h=3.0):
    """Main entry point.  `params` comes from the AI designer
    (roof_ai.design_roof or ask_gemini.get_roof_parameters).
    Returns (list_of_meshes, info_dict)."""
    poly = extract_footprint(walls, scale)
    if poly is None:
        return [], {}

    style    = params.get("roof_style", "gable")
    pitch    = float(np.clip(params.get("pitch_angle", 30), 4, 75))
    overhang = float(np.clip(params.get("overhang", 0.45), 0.15, 1.0))
    seed     = params.get("seed")
    rng      = np.random.default_rng(seed)
    mat      = params.get("material")
    if mat not in ROOF_MATERIALS:
        mat = rng.choice(STYLE_MATERIALS.get(style, ["asphalt-dark"]))
    color = ROOF_MATERIALS[mat]

    m = footprint_metrics(poly)
    parts, ridge_h = [], 2.0
    base_z = wall_h

    if style == "composite":
        # RAG-retrieved multi-zone composition (roof_ai.design_roof_rag)
        zones = params.get("zones", [])
        parts, ridge_h = gen_composite(poly, zones, base_z, mat, rng)

    elif style in ("gable", "saltbox", "gambrel"):
        prof = "gambrel" if style == "gambrel" else "gable"
        shift = float(rng.uniform(0.25, 0.45)) * rng.choice([-1, 1]) \
                if style == "saltbox" else 0.0
        wings = decompose_wings(poly) if m["convexity"] < 0.92 else [m["bounds"]]
        for rect in wings:
            p, rh = gen_gable_wing(rect, base_z, pitch, overhang, color,
                                   ridge_shift=shift, profile=prof)
            parts += p
            ridge_h = max(ridge_h, rh)

    elif style == "cross-gable":
        wings = decompose_wings(poly)
        if len(wings) == 1:      # rectangular plan → synthesise a cross wing
            x0, y0, x1, y1 = wings[0]
            w, d = x1 - x0, y1 - y0
            cw = min(w, d) * rng.uniform(0.42, 0.55)
            cx = rng.uniform(x0 + cw, x1 - cw) if w > d else (x0 + x1) / 2
            cy = (y0 + y1) / 2 if w > d else rng.uniform(y0 + cw, y1 - cw)
            if w > d:
                wings.append((cx - cw / 2, y0 - rng.uniform(0.0, 0.6),
                              cx + cw / 2, y1 + rng.uniform(0.4, 1.2)))
            else:
                wings.append((x0 - rng.uniform(0.0, 0.6), cy - cw / 2,
                              x1 + rng.uniform(0.4, 1.2), cy + cw / 2))
        for rect in wings:
            p, rh = gen_gable_wing(rect, base_z, pitch, overhang, color)
            parts += p
            ridge_h = max(ridge_h, rh)

    elif style in ("hip", "pyramid"):
        parts += gen_hip(poly, base_z, pitch, overhang, color)
        ridge_h = (min(m["width"], m["depth"]) / 2 + overhang) * np.tan(np.radians(pitch))

    elif style == "dutch-gable":
        parts += gen_dutch_gable(poly, base_z, pitch, overhang, color)
        ridge_h = (min(m["width"], m["depth"]) / 2 + overhang) * np.tan(np.radians(pitch))

    elif style == "mansard":
        parts += gen_mansard(poly, base_z, color)
        ridge_h = 2.2

    elif style == "butterfly":
        parts += gen_butterfly(poly, base_z, max(6, min(pitch, 16)), overhang, color)
        ridge_h = 1.2

    elif style == "skillion":
        parts += gen_skillion(poly, base_z, max(6, min(pitch, 22)), overhang,
                              color, rng=rng)
        ridge_h = m["width"] * np.tan(np.radians(min(pitch, 22)))

    else:  # flat-modern & anything unknown
        parts += gen_flat_modern(poly, base_z, color)
        ridge_h = 0.8

    # ── self-check: no reconstruction may leave the footprint open ──
    # (composition bugs, degenerate zones, bad wing decompositions).
    # A leaky roof is rebuilt as a distance-field hip, which is
    # watertight for ANY footprint by construction.
    repaired = False
    if params.get("self_check", True) and parts:
        gap = _coverage_gap(parts, poly, wall_h)
        if gap > 0.03:
            print(f"⚠️ Roof self-check: {gap:.1%} of the footprint was "
                  f"unroofed → rebuilt as safe hip.")
            safe_pitch = float(np.clip(pitch, 18, 30))
            parts = gen_hip(poly, base_z, safe_pitch, overhang, color)
            ridge_h = (min(m["width"], m["depth"]) / 2 + overhang) * \
                np.tan(np.radians(safe_pitch))
            repaired = True

    # ── accessories ────────────────────────────────────────────────
    x0, y0, x1, y1 = m["bounds"]
    if params.get("has_dormers") and not repaired and \
            style in ("gable", "gambrel", "saltbox", "cross-gable", "mansard"):
        n = int(np.clip(params.get("dormer_count", rng.integers(1, 3)), 1, 3))
        along_x = m["width"] >= m["depth"]
        up = 0.55            # window face this far in from the eave,
        zlift = up * np.tan(np.radians(pitch))   # seated on the slope
        for k in range(n):
            frac = (k + 1) / (n + 1)
            if along_x:
                parts += _dormer(x0 + frac * (x1 - x0), y1 - up, +1, pitch,
                                 base_z + 0.30 + zlift, color)
            else:
                parts += _dormer(y0 + frac * (y1 - y0), x1 - up, +1, pitch,
                                 base_z + 0.30 + zlift, color, axis="x")

    if params.get("has_chimney") and style not in ("butterfly", "flat-modern"):
        cxy = poly.representative_point()
        jx = float(rng.uniform(-0.18, 0.18)) * m["width"]
        parts += _chimney(float(np.clip(cxy.x + jx, x0 + 1, x1 - 1)),
                          float(cxy.y), base_z + ridge_h)

    if params.get("has_skylight") and style in ("flat-modern", "skillion", "butterfly"):
        cxy = poly.representative_point()
        parts += _skylight(cxy.x, cxy.y, base_z + 0.25)

    info = {"style": style, "material": mat, "pitch": pitch,
            "overhang": overhang, "ridge_height": ridge_h,
            "wings": len(decompose_wings(poly)), "metrics": m,
            "repaired": repaired}
    return parts, info


# ════════════════════════════════════════════════════════════════════
#  5. COMPOSITE EXECUTOR  (used by the RAG designer, roof_ai.design_roof_rag)
#     Executes multi-zone roof compositions retrieved from the design
#     knowledge base: split-level skillions, clerestory bands, stacked
#     volumes, per-wing style mixes, sawtooth steps, ...
# ════════════════════════════════════════════════════════════════════
def _resolve_region(poly, wings, region):
    """Turn a symbolic region spec into an actual footprint sub-polygon."""
    x0, y0, x1, y1 = poly.bounds
    w, d = x1 - x0, y1 - y0
    rtype = region.get("type", "full")
    if rtype == "full":
        return poly
    if rtype == "wing":
        i = region.get("index", 0)
        if i < len(wings):
            wx0, wy0, wx1, wy1 = wings[i]
            zp = poly.intersection(shp_box(wx0 - 0.01, wy0 - 0.01,
                                           wx1 + 0.01, wy1 + 0.01))
        else:  # plan has fewer wings than the recipe expects → split halves
            f0, f1 = (0.0, 0.5) if i == 0 else (0.5, 1.0)
            return _resolve_region(poly, wings,
                                   dict(type="split", axis="long", f0=f0, f1=f1))
        if zp.is_empty:
            return None
        if isinstance(zp, MultiPolygon):
            zp = max(zp.geoms, key=lambda g: g.area)
        return zp
    if rtype == "split":
        axis = region.get("axis", "long")
        if axis == "long":
            axis = "x" if w >= d else "y"
        elif axis == "short":
            axis = "y" if w >= d else "x"
        f0, f1 = region.get("f0", 0.0), region.get("f1", 0.5)
        if axis == "x":
            cut = shp_box(x0 + f0 * w, y0 - 5, x0 + f1 * w, y1 + 5)
        else:
            cut = shp_box(x0 - 5, y0 + f0 * d, x1 + 5, y0 + f1 * d)
        zp = poly.intersection(cut)
        if zp.is_empty:
            return None
        if isinstance(zp, MultiPolygon):
            zp = max(zp.geoms, key=lambda g: g.area)
        return zp
    return poly


def _resolve_direction(dir_spec, poly):
    """'+long' / '-short' / '+x' ... → concrete '+x'/'-x'/'+y'/'-y'."""
    if dir_spec in ("+x", "-x", "+y", "-y"):
        return dir_spec
    x0, y0, x1, y1 = poly.bounds
    long_is_x = (x1 - x0) >= (y1 - y0)
    sign = dir_spec[0] if dir_spec and dir_spec[0] in "+-" else "+"
    axis = dir_spec.lstrip("+-") if dir_spec else "long"
    if axis == "long":
        return sign + ("x" if long_is_x else "y")
    return sign + ("y" if long_is_x else "x")


def gen_skillion_directed(poly, base_z, pitch, overhang, color,
                          direction="+y", fascia=0.18, footprint=None,
                          raised=False, posts="auto", porch=None,
                          soffit=True):
    """Single sloped plane. Beyond the bare wedge this now builds the
    structure that makes it read as architecture, not a floating shell:
      · soffit  — timber ceiling layer under the whole plane
      · posts   — pillars under the high edge whenever the plane floats
                  (raised clerestory zone, deep overhang, porch bay)
      · porch   — optional roof extension past one side, held by posts
    """
    fp = footprint if footprint is not None else poly
    p = poly.buffer(overhang, join_style=2)
    porch_edge = None
    if porch:
        porch_edge = _resolve_direction(porch.get("side", "-y"), fp)
        p = _directional_extend(p, porch_edge, float(porch.get("depth", 1.8)))
    x0, y0, x1, y1 = p.bounds
    t = np.tan(np.radians(pitch))
    fn = {"+x": lambda x, y: (x - x0) * t, "-x": lambda x, y: (x1 - x) * t,
          "+y": lambda x, y: (y - y0) * t, "-y": lambda x, y: (y1 - y) * t}[direction]
    parts = [_heightfield_roof(p, fn, base_z, fascia, color)]
    if soffit:
        parts += _soffit_plate(p, base_z)
    edges = []
    if posts == "auto":
        # the high edge is the side the plane rises toward
        if raised or porch is not None or overhang >= 0.5:
            edges.append(direction)
    elif posts:
        edges = [_resolve_direction(e, fp) for e in posts]
    if porch_edge and porch_edge not in edges:
        edges.append(porch_edge)
    for e in dict.fromkeys(edges):
        parts += _posts_along_edge(p, e, base_z + 0.08, footprint=fp)
    return parts


def _riser_band(zp, base_z, h, clerestory=False, wall_frac=0.30):
    """Perimeter band under a raised zone. Lower part is wall; if the
    recipe asks for a clerestory, the upper part is a glass band —
    the signature light strip of modern split-level roofs."""
    parts = []
    try:
        ring = zp.difference(zp.buffer(-0.14, join_style=2))
        if clerestory and h > 0.45:
            wall_h = max(0.18, h * wall_frac)
            wall = trimesh.creation.extrude_polygon(ring, height=wall_h)
            wall.apply_translation([0, 0, base_z])
            parts.append(_colored(wall, WALL_COLOR))
            glass = trimesh.creation.extrude_polygon(
                zp.difference(zp.buffer(-0.08, join_style=2)),
                height=h - wall_h)
            glass.apply_translation([0, 0, base_z + wall_h])
            parts.append(_colored(glass, GLASS_COLOR))
            # slim mullions
            mull = trimesh.creation.extrude_polygon(ring, height=0.05)
            mull.apply_translation([0, 0, base_z + h - 0.05])
            parts.append(_colored(mull, [60, 60, 65, 255]))
        else:
            band = trimesh.creation.extrude_polygon(ring, height=h)
            band.apply_translation([0, 0, base_z])
            parts.append(_colored(band, WALL_COLOR))
    except Exception:
        pass
    return parts


def gen_composite(poly, zones, base_z, default_material, rng):
    """Execute a multi-zone composition from the knowledge base."""
    wings = decompose_wings(poly)
    parts, max_top = [], 0.6
    for zspec in zones:
        zp = _resolve_region(poly, wings, zspec.get("region", {"type": "full"}))
        if zp is None or zp.area < 2.5:
            continue
        style = zspec.get("style", "flat")
        pitch = float(zspec.get("pitch", 14))
        ovh = float(zspec.get("overhang", 0.35))
        h_off = float(zspec.get("h_offset", 0.0))
        mat = zspec.get("material") or default_material
        color = ROOF_MATERIALS.get(mat, ROOF_MATERIALS["metal-seam"])
        z0 = base_z + h_off
        zm = footprint_metrics(zp)

        if h_off > 0.05:
            parts += _riser_band(zp, base_z - 0.15, h_off + 0.15,
                                 clerestory=bool(zspec.get("clerestory")))

        if style == "skillion":
            # direction MUST resolve against the full footprint: split
            # zones flip aspect, so "+short" measured on the zone itself
            # produced perpendicular planes with an open wedge into the
            # house (the hollow-rake artefact).
            d = _resolve_direction(zspec.get("direction", "+short"), poly)
            parts += gen_skillion_directed(
                zp, z0, pitch, ovh, color, d, footprint=poly,
                raised=h_off > 0.05, posts=zspec.get("posts", "auto"),
                porch=zspec.get("porch"))
            top = min(zm["width"], zm["depth"]) * np.tan(np.radians(pitch))
        elif style == "butterfly":
            parts += gen_butterfly(zp, z0, pitch, ovh, color)
            top = 0.9
        elif style == "flat":
            if zspec.get("parapet", True):
                parts += gen_flat_modern(zp, z0, color,
                                         parapet_h=0.5, overhang=ovh)
            else:
                pbuf = zp.buffer(ovh, join_style=2)
                porch = zspec.get("porch")
                if porch:
                    pbuf = _directional_extend(
                        pbuf, _resolve_direction(porch.get("side", "-y"), poly),
                        float(porch.get("depth", 1.8)))
                slab = trimesh.creation.extrude_polygon(pbuf, height=0.22)
                slab.apply_translation([0, 0, z0])
                parts.append(_colored(slab, color))
                parts += _soffit_plate(pbuf, z0)
                pspec = zspec.get("posts")
                edges = [_resolve_direction(e, poly) for e in pspec] \
                    if isinstance(pspec, (list, tuple)) else []
                if porch:
                    edges.append(_resolve_direction(porch.get("side", "-y"),
                                                    poly))
                for e in dict.fromkeys(edges):
                    parts += _posts_along_edge(pbuf, e, z0 + 0.08,
                                               footprint=poly)
            top = 0.75
        elif style in ("gable", "gambrel", "saltbox"):
            prof = "gambrel" if style == "gambrel" else "gable"
            shift = 0.35 * rng.choice([-1, 1]) if style == "saltbox" else 0.0
            p2, rh = gen_gable_wing(zm["bounds"], z0, pitch, ovh, color,
                                    ridge_shift=shift, profile=prof)
            parts += p2
            top = rh
        elif style in ("hip", "pyramid"):
            parts += gen_hip(zp, z0, pitch, ovh, color)
            top = (min(zm["width"], zm["depth"]) / 2 + ovh) * \
                  np.tan(np.radians(pitch))
        elif style == "dutch-gable":
            parts += gen_dutch_gable(zp, z0, pitch, ovh, color)
            top = (min(zm["width"], zm["depth"]) / 2) * np.tan(np.radians(pitch))
        elif style == "mansard":
            parts += gen_mansard(zp, z0, color)
            top = 2.2
        else:
            parts += gen_flat_modern(zp, z0, color)
            top = 0.75
        max_top = max(max_top, h_off + top)
    return parts, max_top


# ════════════════════════════════════════════════════════════════════
#  6. HEIGHTMAP → MESH  (bridge for the learned diffusion generator)
# ════════════════════════════════════════════════════════════════════
def mesh_from_heightmap(hm, mask, bounds, base_z=3.0, color=None,
                        smooth_sigma=1.0):
    """Convert a (H, W) roof heightmap in metres + binary footprint mask
    into a closed roof mesh registered onto the building.
    This is how a trained diffusion model's output enters the pipeline."""
    from scipy.ndimage import gaussian_filter
    hm = np.asarray(hm, dtype=float)
    mask = np.asarray(mask) > 0.5
    if smooth_sigma:
        hm = gaussian_filter(hm, smooth_sigma)
    H, W = hm.shape
    x0, y0, x1, y1 = bounds
    xs = np.linspace(x0, x1, W)
    ys = np.linspace(y0, y1, H)

    idx = -np.ones((H, W), dtype=int)
    verts = []
    for j in range(H):
        for i in range(W):
            if mask[j, i]:
                idx[j, i] = len(verts)
                verts.append([xs[i], ys[j], base_z + 0.12 + max(hm[j, i], 0)])
    top_faces = []
    for j in range(H - 1):
        for i in range(W - 1):
            a, b = idx[j, i], idx[j, i + 1]
            c, d = idx[j + 1, i], idx[j + 1, i + 1]
            if min(a, b, c, d) >= 0:
                top_faces += [[a, b, d], [a, d, c]]
    verts = np.array(verts, dtype=float)
    nv = len(verts)
    bot = verts.copy()
    bot[:, 2] = base_z
    faces = np.array(top_faces, dtype=np.int64)
    all_v = np.vstack([verts, bot])
    all_f = [faces, faces[:, ::-1] + nv]
    # rim
    ecount = {}
    for tri in faces:
        for a, b in ((tri[0], tri[1]), (tri[1], tri[2]), (tri[2], tri[0])):
            ecount[(min(a, b), max(a, b))] = ecount.get((min(a, b), max(a, b)), 0) + 1
    side = []
    for tri in faces:
        for a, b in ((tri[0], tri[1]), (tri[1], tri[2]), (tri[2], tri[0])):
            if ecount[(min(a, b), max(a, b))] == 1:
                side += [[a, b, b + nv], [a, b + nv, a + nv]]
    all_f.append(np.array(side, dtype=np.int64))
    mesh = trimesh.Trimesh(vertices=all_v, faces=np.vstack(all_f), process=True)
    return _colored(mesh, color or ROOF_MATERIALS["asphalt-gray"])


def rasterize_roof_heightmap(meshes, bounds, res=128):
    """Inverse bridge: numpy z-buffer rasterizer turning a procedural
    roof (list of trimesh meshes) into a (res, res) heightmap above the
    wall top — used to mass-produce synthetic diffusion training data."""
    x0, y0, x1, y1 = bounds
    hm = np.zeros((res, res), dtype=float)
    sx = (res - 1) / max(x1 - x0, 1e-6)
    sy = (res - 1) / max(y1 - y0, 1e-6)
    for mesh in meshes:
        if not isinstance(mesh, trimesh.Trimesh):
            continue
        tris = mesh.vertices[mesh.faces]
        for t in tris:
            px = (t[:, 0] - x0) * sx
            py = (t[:, 1] - y0) * sy
            iy0, iy1 = int(max(py.min(), 0)), int(min(py.max(), res - 1)) + 1
            ix0, ix1 = int(max(px.min(), 0)), int(min(px.max(), res - 1)) + 1
            if ix1 <= ix0 or iy1 <= iy0:
                continue
            gx, gy = np.meshgrid(np.arange(ix0, ix1), np.arange(iy0, iy1))
            # barycentric containment
            d = ((py[1] - py[2]) * (px[0] - px[2]) +
                 (px[2] - px[1]) * (py[0] - py[2]))
            if abs(d) < 1e-9:
                continue
            l1 = ((py[1] - py[2]) * (gx - px[2]) + (px[2] - px[1]) * (gy - py[2])) / d
            l2 = ((py[2] - py[0]) * (gx - px[2]) + (px[0] - px[2]) * (gy - py[2])) / d
            l3 = 1 - l1 - l2
            inside = (l1 >= -1e-6) & (l2 >= -1e-6) & (l3 >= -1e-6)
            z = l1 * t[0, 2] + l2 * t[1, 2] + l3 * t[2, 2]
            sub = hm[iy0:iy1, ix0:ix1]
            np.maximum(sub, np.where(inside, z, 0), out=sub)
    return hm
