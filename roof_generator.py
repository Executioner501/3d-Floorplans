"""
roof_generator.py — Generative roof synthesis engine
====================================================
Replaces the default slab-only roof stage with a footprint-aware,
style-diverse, procedurally generative roof module.

Supported styles
----------------
  gable, cross-gable, hip, pyramid, dutch-gable, gambrel, mansard,
  saltbox, butterfly, skillion, flat-modern
(legacy styles "flat", "split-level", "mono-pitch", "shed" continue to
be handled by builder.py's original code path)

Key ideas
---------
1. FOOTPRINT EXTRACTION — the union of detected wall boxes is closed
   into a filled orthogonal polygon; wings are recovered by greedy
   maximal-rectangle decomposition, so cross-gables / hips follow the
   actual L / T / U plan shape instead of a naive mid-X split.

2. DISTANCE-FIELD HIP SURFACE — for hip / pyramid / mansard / dutch
   roofs the height of every roof point is  d(p, boundary) * tan(pitch)
   (optionally capped).  This is mathematically the straight-skeleton
   hip roof: ridges, hips and valleys emerge automatically for ANY
   footprint shape, including concave L/T/U plans.

3. PROFILE PRISMS — gable / gambrel / saltbox wings are generated by
   sweeping a parametric cross-section profile along each wing's ridge
   axis, with proper eave + rake overhangs and gable-end infill walls.

4. CONTROLLED RANDOMNESS — every call may take a seed; pitch, overhang,
   ridge offsets, material palette, dormers, chimneys and skylights are
   jittered inside architecturally valid ranges, so identical floor
   plans still yield distinct-but-plausible roofs.

All meshes are returned in the builder's model space
(x/y metres, z-up, wall top at z = wall_h).
"""

